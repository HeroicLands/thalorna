def fbm(shape, rng, scales):
    """Smooth noise as a sum of blurred white noise, zero mean."""
    out = np.zeros(shape, np.float32)
    for sigma, amp in scales:
        n = rng.standard_normal(shape).astype(np.float32)
        n = ndimage.gaussian_filter(n, sigma) if np.max(sigma) > 0 else n
        n /= n.std() + 1e-6
        out += amp * n
    return out


def poly_mask(shape, polys, ss=1):
    img = Image.new("L", (shape[1], shape[0]), 0)
    d = ImageDraw.Draw(img)
    for p in polys:
        d.polygon([(x * ss, y * ss) for x, y in p], fill=255)
    return np.asarray(img, np.float32) / 255.0


def star_points(cx, cy, r):
    pts = []
    for i in range(10):
        a = -math.pi / 2 + i * math.pi / 5
        rr = r if i % 2 == 0 else r * 0.40
        pts.append((cx + rr * math.cos(a), cy + rr * math.sin(a)))
    return pts


def stadium_dist(shape, x0, y0, x1, y1):
    """Signed distance inside a horizontal stadium (positive inside)."""
    h, w = shape
    yy, xx = np.mgrid[0:h, 0:w].astype(np.float32)
    r = (y1 - y0) / 2
    cy = (y0 + y1) / 2
    px = np.clip(xx, x0 + r, x1 - r)
    return r - np.hypot(xx - px, yy - cy)


def gold_from(t):
    t = np.clip(t, 0, 1)
    out = np.zeros(t.shape + (3,), np.float32)
    xs = [p for p, _ in GOLD_RAMP]
    for ch in range(3):
        out[..., ch] = np.interp(t, xs, [c[ch] for _, c in GOLD_RAMP])
    return out


