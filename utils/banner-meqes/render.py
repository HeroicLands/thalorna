def load_paint(path):
    """Load the font's paint maps and the paint.py beside them, which finds each sign's
    regions the same way every reader of the maps does."""
    global PAINTMOD
    path = Path(path)
    module = path.parent / "paint.py"
    if not path.exists() or not module.exists():
        raise SystemExit(f"paint: {path} and the paint.py beside it are needed")
    spec = importlib.util.spec_from_file_location("zethu_paint", module)
    PAINTMOD = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(PAINTMOD)
    PAINT.clear()
    PAINT.update(PAINTMOD.load(path))
    missing = [c for c in PAINT["categories"] if c not in CATEGORY_COLOURS and c not in ("gold", "ground")]
    if missing:
        raise SystemExit(f"paint: categories with no colour in this palette: {', '.join(missing)}")


def colour_of(raw, where):
    c = str(raw or "").strip().lower()
    if c in CATEGORIES:
        return c
    if c.startswith("god:"):
        return c if c[4:] in GODS else "gold"
    raise SystemExit(f"sequence: {where}: colour {raw!r} is not one of {', '.join(CATEGORIES)} or god:<name>")


def shape_of(entry, variant):
    """tall, low or small, from the sign's box in the font's table."""
    bw, bh = entry["box"].get(variant, entry["box"]["a"])
    if bw <= 60 and bh <= 60:
        return "small"
    return "low" if bh <= 60 else "tall"


def make_sign(s, e, where):
    return dict(
        id=s["id"],
        glyph="z" + s["id"].replace("-", "_") + "." + (s.get("variant") or "a"),
        colour=colour_of(s.get("colour") or s.get("category"), f"{where}, {s['id']}"),
        tone=s.get("tone"),
        mirror=bool(s.get("mirror", False)),
        shape=s.get("shape") or shape_of(e, s.get("variant") or "a"),
        regions=s.get("regions"),
    )


def load_sequence(path, enc):
    """Each register as units in reading order: a quadrat, a vignette or a cord oval (the run
    of `frame: true` quadrats). A quadrat is a tree: ('v', rows), ('h', signs) or ('s', sign)."""
    data = json.loads(Path(path).read_text(encoding="utf-8"))
    by_id = {e["id"]: e for e in enc["signs"]}
    registers = []
    for ri, reg in enumerate(data["registers"]):
        units = []
        for qi, q in enumerate(reg["quadrats"]):
            where = f"register {ri + 1}, quadrat {qi + 1}"
            rows, scales = [], []
            for row in q["rows"]:
                signs = []
                for s in row:
                    e = by_id.get(s["id"])
                    if e is None or not e["drawn"]:
                        raise SystemExit(f"sequence: {where}: {s['id']} is not a drawn sign of the font")
                    if s.get("codepoint") and s["codepoint"].upper() != e["codepoint"].upper():
                        raise SystemExit(f"sequence: {where}: {s['id']} is {e['codepoint']}, not {s['codepoint']}")
                    if s.get("vignette"):
                        scales.append(float(s.get("scale") or 1.6))
                    signs.append(("s", make_sign(s, e, where)))
                rows.append(signs[0] if len(signs) == 1 else ("h", signs))
            tree = rows[0] if len(rows) == 1 else ("v", rows)
            if scales:
                if q.get("frame"):
                    raise SystemExit(f"sequence: {where}: a vignette cannot stand in the cord oval")
                if len(q["rows"]) != 1:
                    raise SystemExit(f"sequence: {where}: a vignette is one row of signs on a ground line")
                span = int(q.get("span") or max([int(x.get("span") or 2) for row in q["rows"] for x in row]))
                units.append(dict(kind="vignette", tree=tree, scale=max(scales), span=span))
            elif q.get("frame"):
                if units and units[-1]["kind"] == "oval" and units[-1]["open"]:
                    units[-1]["trees"].append(tree)
                else:
                    units.append(dict(kind="oval", trees=[tree], open=True))
            else:
                if units and units[-1]["kind"] == "oval":
                    units[-1]["open"] = False
                units.append(dict(kind="quadrat", tree=tree))
        registers.append(dict(title=reg.get("title", f"register {ri + 1}"), units=units, episode=reg.get("episode", ri + 1)))
    if not 4 <= len(registers) <= 16:
        raise SystemExit(f"sequence: the wall takes 4 to 16 registers; the sequence has {len(registers)}")
    # Scenes listed apart from the text: each spans registers of one episode at the start (right)
    # or the end (left) of their lines.
    scenes = []
    for vi, v in enumerate(data.get("vignettes", [])):
        where = f"vignette {vi + 1}"
        rows = [int(x) - 1 for x in v["spans"]]
        a, b = min(rows), max(rows)
        if a < 0 or b >= len(registers):
            raise SystemExit(f"sequence: {where}: spans {v['spans']}, but the wall has {len(registers)} registers")
        if len({registers[i]["episode"] for i in range(a, b + 1)}) != 1:
            raise SystemExit(f"sequence: {where}: spans {v['spans']}, which would cross an episode band")
        if v.get("side", "start") not in ("start", "end"):
            raise SystemExit(f"sequence: {where}: side is start or end, not {v.get('side')!r}")
        signs = []
        for s in v["signs"]:
            e = by_id.get(s["id"])
            if e is None or not e["drawn"]:
                raise SystemExit(f"sequence: {where}: {s['id']} is not a drawn sign of the font")
            signs.append(("s", make_sign(s, e, where)))
        tree = signs[0] if len(signs) == 1 else ("h", signs)
        scenes.append(dict(kind="vignette", tree=tree, scale=float(v.get("scale") or 2.0), rows=(a, b), side=v.get("side", "start")))
    return data, registers, scenes


# -- glyphs ----------------------------------------------------------------------------------


class Glyphs:
    """The font's outlines, read through its paint module so layout, raster and regions agree."""

    def __init__(self, font_path):
        self.pg = PAINTMOD.Glyphs(Path(font_path))
        self._b = {}

    def bounds(self, name):
        if name not in self._b:
            if name not in self.pg:
                raise SystemExit(f"font: no glyph {name}")
            self._b[name] = self.pg.bounds(name)
        return self._b[name]


# -- layout ----------------------------------------------------------------------------------
#
# The wall's height is divided evenly among the registers. Thick coloured bands stand between
# episodes and at the top and foot; a thin rule in a darker tone of the episode's band divides
# the registers of one episode. Quadrats pack shoulder to shoulder with a fixed gutter, and a
# line is justified by scaling its quadrats, never by opening its gutters. A vignette spans two
# registers of one episode, across the thin rule between them, and both lines run beside it.

UNIT = 740.0  # font units to a quadrat of ink
GAP_IN = 0.03  # between the signs of one quadrat, in quadrats
GUTTER = 0.04  # between quadrats, in quadrats; fixed
PAD = 0.035  # between a register's rules and its text, in quadrats
GROW_MAX = 1.0 / (1 - 2 * PAD)  # a short line's quadrats grow until they meet the rules
WIDE = 1.25  # a lone low sign may be this many quadrats wide
OVAL_IN = 0.80  # the oval's cell, as a share of the line's quadrat
SMALL = 0.50  # a small sign's largest side, in quadrats
STRETCH_MAX = 1.3  # how far a short line lets its width-bound quadrats widen
KILT_BAND = (0.33, 0.50)  # where a standing figure's kilt begins, as shares of its height
KILT_HEM = (0.50, 0.68)  # where it ends
KILT_DISC = 1.6  # the radius, in hairlines, of the disc that tells a kilt from a leg
OUTLINE_TRIM = 0.10  # trimmed from each side of the drawn hairline, in hairlines
VIG_GAP = 0.06  # between a vignette and the text beside it, in quadrats
HEADING_MAX = 1.4  # the most a register with no scene may grow beyond the others' height


def leaf_k(sign, glyphs, Q, stretch=1.0):
    """The scale of a sign alone in its cell: a tall sign spans the height, a low one the
    width, a small one half the cell."""
    x0, y0, x1, y1 = glyphs.bounds(sign["glyph"])
    w, h = x1 - x0, y1 - y0
    wmax = (WIDE if sign["shape"] == "low" else 1.0) * Q * stretch
    fit = min(wmax / w, Q / h)
    if sign["shape"] == "small":
        return min(fit, SMALL * Q / max(w, h))
    return fit


def fit(node, glyphs, Q, wmax=None, stretch=1.0):
    """Lay a quadrat tree into a cell Q high and at most wmax wide, keeping every sign's
    proportions. Returns (w, h, items), items being (sign, k, x, y) from the cell's top left."""
    gap = GAP_IN * Q
    if node[0] == "s":
        k = leaf_k(node[1], glyphs, Q, stretch)
        x0, y0, x1, y1 = glyphs.bounds(node[1]["glyph"])
        return (x1 - x0) * k, (y1 - y0) * k, [(node[1], k, 0.0, 0.0)]
    parts = [fit(c, glyphs, Q, Q * stretch, stretch) for c in node[1]]
    items = []
    if node[0] == "h":
        w = sum(p[0] for p in parts) + gap * (len(parts) - 1)
        h = max(p[1] for p in parts)
        x = w
        for pw, ph, its in parts:
            x -= pw
            items += [(s, k, x + ix, h - ph + iy) for s, k, ix, iy in its]
            x -= gap
    else:
        w = max(p[0] for p in parts)
        h = sum(p[1] for p in parts) + gap * (len(parts) - 1)
        y = 0.0
        for pw, ph, its in parts:
            items += [(s, k, (w - pw) / 2 + ix, y + iy) for s, k, ix, iy in its]
            y += ph + gap
    f = min(1.0, (wmax or Q * 1.1 * stretch) / w, Q / h)
    return w * f, h * f, [(s, k * f, ix * f, iy * f) for s, k, ix, iy in items]


def unit_fit(u, glyphs, Q, stretch=1.0):
    """A text unit's width at line height Q, with what is needed to place it. Stretch lets a
    quadrat held by its width (a low sign, a pair of small ones) grow toward the full height."""
    if u["kind"] == "quadrat":
        w, h, items = fit(u["tree"], glyphs, Q, None, stretch)
        return w, dict(h=h, items=items)
    q = Q * OVAL_IN
    inner = [fit(t, glyphs, q, None, stretch) for t in u["trees"]]
    igap = GUTTER * Q
    iw = sum(i[0] for i in inner) + igap * (len(inner) - 1)
    ch = Q * 0.99
    return iw + ch * 0.55 + 0.06 * Q, dict(inner=inner, igap=igap, ch=ch)


# In a scene a person stands the full height; a beast, a bird or a thing keeps a size of its own
# beside the people, by the sign's group.
SCENE_SIZE = {"01": 1.0, "02": 1.0, "03": 0.8, "05": 0.72, "06": 0.7, "07": 0.6, "11": 0.85}
SCENE_SIZE_OTHER = 0.5
# The most a scene's growth may bring each group to, so a sack never stands as tall as a man.
SCENE_SIZE_MAX = {"03": 0.9, "05": 0.9, "06": 0.8, "07": 0.8, "11": 1.0}
SCENE_SIZE_MAX_OTHER = 0.7
SCENE_GUTTER = 0.02  # between a scene's figures, in scene heights: the text's 4% gutter
GROW_SCENE_MAX = 1.0 / SCENE_SIZE_OTHER  # beyond this every figure stands a person's height


def natural_width(units, glyphs, Q):
    ws = [unit_fit(u, glyphs, Q)[0] for u in units]
    return sum(ws) + GUTTER * Q * (len(ws) - 1)


def line_width(units, glyphs, Q, stretch=1.0):
    """A line's width at line height Q, shoulder to shoulder."""
    return sum(unit_fit(u, glyphs, Q, stretch)[0] for u in units) + GUTTER * Q * (len(units) - 1)


def vignette_fit(u, glyphs, height, grow=1.0):
    """A scene's figures stand on one ground, right to left, a gutter apart. A person fills the
    height; every other sign stands at its group's size times grow, never taller than a person."""
    signs = u["tree"][1] if u["tree"][0] == "h" else [u["tree"]]
    sizes, ks = [], []
    for sg in signs:
        b = glyphs.bounds(sg[1]["glyph"])
        size = SCENE_SIZE.get(sg[1]["id"][:2], SCENE_SIZE_OTHER)
        cap = SCENE_SIZE_MAX.get(sg[1]["id"][:2], SCENE_SIZE_MAX_OTHER)
        size = 1.0 if size >= 1.0 else min(cap, size * grow)
        # every figure at one scale, a full sign's ink filling the height, so a lying man is long
        # and low; a sign drawn taller than a full sign is held to the height
        k = height * size / max(UNIT, b[3] - b[1])
        ks.append(k)
        sizes.append(((b[2] - b[0]) * k, (b[3] - b[1]) * k))
    gap = SCENE_GUTTER * height
    w = sum(sw for sw, _ in sizes) + gap * (len(sizes) - 1)
    items, x = [], w
    for sg, k, (sw, sh) in zip(signs, ks, sizes):
        x -= sw
        items.append((sg[1], k, x, height - sh))
        x -= gap
    return w, items


def frame(registers, weights=None):
    """Where each register, band and rule lies. The height left after the bands and rules is
    shared among the registers by weight. Returns (Qs, regs, bands, rules): Qs is each line's
    height; regs are (top, bottom); bands are (y, colour index); rules are (y, colour index,
    upper register)."""
    n = len(registers)
    starts = [i == 0 or registers[i]["episode"] != registers[i - 1]["episode"] for i in range(n)]
    n_thick = sum(starts) + 1
    n_thin = n - sum(starts)
    weights = weights or [1.0] * n
    unit_h = ((REG_BOT - REG_TOP) - n_thick * BAND - n_thin * RULE) / sum(weights)
    regs, bands, rules = [], [], []
    y, ep = float(REG_TOP), -1
    for i in range(n):
        if starts[i]:
            ep += 1
            bands.append((y, ep))
            y += BAND
        else:
            rules.append((y, ep, i - 1))
            y += RULE
        regs.append((y, y + unit_h * weights[i]))
        y += unit_h * weights[i]
    bands.append((y, ep + 1))
    return [unit_h * w * (1 - 2 * PAD) for w in weights], regs, bands, rules


def pair_vignettes(registers):
    """Give each vignette the two registers it spans: its own and the next of its episode, or
    the one before when it is the episode's last. A vignette alone in its episode spans one."""
    out = []
    for r, reg in enumerate(registers):
        for i, u in enumerate(reg["units"]):
            if u["kind"] != "vignette":
                continue
            ep = reg["episode"]
            if u["span"] >= 2 and r + 1 < len(registers) and registers[r + 1]["episode"] == ep:
                rows = (r, r + 1)
            elif u["span"] >= 2 and r > 0 and registers[r - 1]["episode"] == ep:
                rows = (r - 1, r)
            else:
                rows = (r, r)
                if u["span"] >= 2:
                    print(f"note: register {r + 1}: a vignette alone in its episode spans one register")
            out.append(dict(reg=r, index=i, unit=u, rows=rows))
    return out


def pack(units, segs, glyphs, Q, grow_max):
    """Flow units right to left through segments (x0, x1), shoulder to shoulder. The whole run
    is scaled to fill the segments, at most grow_max; a run too long is scaled down. Each
    segment then fits its own share. Returns placed (unit, info, x_right, scale) tuples."""
    if not units:
        return []
    total = sum(x1 - x0 for x0, x1 in segs)
    nat = [unit_fit(u, glyphs, Q)[0] for u in units]
    f = min(grow_max, (total - GUTTER * Q * (len(units) - len(segs))) / sum(nat))
    while True:
        assign, si, used = [[] for _ in segs], 0, 0.0
        ok = True
        for u, w in zip(units, nat):
            w *= f
            need = w + (GUTTER * Q * f if assign[si] else 0)
            while si < len(segs) and used + need > segs[si][1] - segs[si][0] + 0.5:
                si += 1
                used = 0.0
                need = w
            if si >= len(segs):
                ok = False
                break
            assign[si].append(u)
            used += need
        if ok:
            break
        f *= 0.98
    placed = []
    for (x0, x1), us in zip(segs, assign):
        if not us:
            continue
        g = GUTTER * Q
        widths = [unit_fit(u, glyphs, Q)[0] for u in us]
        s = min(grow_max, (x1 - x0 - g * (len(us) - 1)) / sum(widths))
        # still short at full height: let the quadrats held by their width grow wider
        m = 1.0

        def run(mm):
            return sum(unit_fit(u, glyphs, Q * s, mm)[0] for u in us) + g * s * (len(us) - 1)

        if s >= grow_max - 1e-6 and run(1.0) < x1 - x0 - 1:
            lo, hi = 1.0, STRETCH_MAX
            if run(hi) <= x1 - x0:
                m = hi
            else:
                for _ in range(20):
                    mid = (lo + hi) / 2
                    lo, hi = (mid, hi) if run(mid) <= x1 - x0 else (lo, mid)
                m = lo
        x = x1
        for u in us:
            w, info = unit_fit(u, glyphs, Q * s, m)
            placed.append((u, info, x, s, m))
            x -= w + g * s
    return placed


def subtract(span, cuts):
    """The interval span less the cut intervals, right to left."""
    segs = [span]
    for c0, c1 in sorted(cuts):
        nxt = []
        for a, b in segs:
            if c1 <= a or c0 >= b:
                nxt.append((a, b))
                continue
            if c0 > a:
                nxt.append((a, c0))
            if c1 < b:
                nxt.append((c1, b))
        segs = nxt
    return sorted([s for s in segs if s[1] - s[0] > 1], key=lambda s: -s[1])


def layout(registers, glyphs, scenes=()):
    """Place every sign on the wall. Returns Q, the frame, the placed signs, the ovals and the
    vignette boxes (x0, y0, x1, y1, upper, lower)."""
    x0, x1 = WALL_X0, WALL_X1
    vigs = pair_vignettes(registers)
    for sc in scenes:
        vigs.append(dict(reg=None, index=None, unit=sc, rows=sc["rows"], side=sc["side"]))
    # A register with no scene takes more of the wall's height when its text is short, so its
    # line, set larger as a heading is, runs edge to edge; the scene registers give it up.
    scened = {r for v in vigs for r in range(v["rows"][0], v["rows"][1] + 1)}
    weights = [1.0] * len(registers)
    for _ in range(5):
        Qs, regs, bands, rules = frame(registers, weights)
        for r, reg in enumerate(registers):
            text = [u for u in reg["units"] if u["kind"] != "vignette"]
            if r in scened or not text:
                continue
            need = natural_width(text, glyphs, Qs[r] * GROW_MAX)
            weights[r] = min(HEADING_MAX, max(1.0, weights[r] * (x1 - x0) / need))
    Qs, regs, bands, rules = frame(registers, weights)
    Q = min(Qs[r] for r in scened) if scened else min(Qs)
    # Each vignette's height and width, and its place: in its own register's reading order.
    for v in vigs:
        a, b = v["rows"]
        top, bot = regs[a][0] + PAD * Q * 0.5, regs[b][1] - PAD * Q
        v["h"] = bot - top
        v["w"], v["items"] = vignette_fit(v["unit"], glyphs, v["h"])
        v["top"] = top
    # Scenes set at the ends of their lines grow, all the figures of a pair of lines together,
    # until they and the text fill the lines; a person already stands the full height, so the
    # beasts, birds and things grow toward it.
    for rows in sorted({v["rows"] for v in vigs if v.get("side")}):
        group = [v for v in vigs if v.get("side") and v["rows"] == rows]

        def slack(grow):
            ws = [vignette_fit(v["unit"], glyphs, v["h"], grow)[0] for v in group]
            out = []
            for r in range(rows[0], rows[1] + 1):
                text = [u for u in registers[r]["units"] if u["kind"] != "vignette"]
                # the farthest the line can reach: full height, its width-bound quadrats widened
                need = line_width(text, glyphs, Qs[r] * GROW_MAX, STRETCH_MAX) if text else 0.0
                taken = sum(w + 2 * VIG_GAP * Q for w in ws)
                taken += sum(v["w"] + 2 * VIG_GAP * Q for v in vigs if v not in group and v["rows"][0] <= r <= v["rows"][1])
                out.append((x1 - x0) - taken - need)
            # The scenes grow until the room left is what the shorter line can reach, so both
            # lines end at the frame; the longer line is set a little smaller to match.
            return max(out)

        grow = 1.0
        if slack(1.0) > 0:
            lo, hi = 1.0, GROW_SCENE_MAX
            if slack(hi) >= 0:
                grow = hi
            else:
                for _ in range(24):
                    mid = (lo + hi) / 2
                    lo, hi = (mid, hi) if slack(mid) >= 0 else (lo, mid)
                grow = lo
        for v in group:
            v["w"], v["items"] = vignette_fit(v["unit"], glyphs, v["h"], grow)
            v["grow"] = grow
        rest = slack(grow)
        if grow > 1.0 or rest > 0:
            print(f"note: scenes in registers {rows[0] + 1}-{rows[1] + 1}: figures grown {grow:.2f}x; "
                  f"{max(0.0, rest) / (Q * GROW_MAX):.1f} quadrats of line left open")
    fill = []
    for r, reg in enumerate(registers):
        text = [u for u in reg["units"] if u["kind"] != "vignette"]
        need = natural_width(text, glyphs, Qs[r] * GROW_MAX) if text else 0.0
        taken = sum(v["w"] + 2 * VIG_GAP * Q for v in vigs if v["rows"][0] <= r <= v["rows"][1])
        fill.append((need / (Qs[r] * GROW_MAX), ((x1 - x0) - taken) / (Qs[r] * GROW_MAX)))
    # The start scenes stand at the right edge. The two lines of a pair then end at one
    # point: as wide as the room between the scenes, or as wide as the shorter line can grow.
    # The end scenes close up against that point, and any wall left over lies at the frame.
    blocks = {}
    for rows in sorted({v["rows"] for v in vigs if v.get("side")}):
        x = x1
        for v in [v for v in vigs if v.get("side") == "start" and v["rows"] == rows]:
            v["x1"], v["x0"] = x, x - v["w"]
            x -= v["w"] + 2 * VIG_GAP * Q
        right = x + VIG_GAP * Q if x < x1 else x1
        ends = [v for v in vigs if v.get("side") == "end" and v["rows"] == rows]
        left_limit = x0 + sum(v["w"] + 2 * VIG_GAP * Q for v in ends) - (VIG_GAP * Q if ends else 0)
        best = right - left_limit
        for r in range(rows[0], rows[1] + 1):
            text = [u for u in registers[r]["units"] if u["kind"] != "vignette"]
            if text:
                best = min(best, line_width(text, glyphs, Qs[r] * GROW_MAX, STRETCH_MAX))
        left = right - best
        x = left - (VIG_GAP * Q if ends else 0)
        for v in ends:
            v["x1"], v["x0"] = x, x - v["w"]
            x -= v["w"] + 2 * VIG_GAP * Q
        for r in range(rows[0], rows[1] + 1):
            blocks[r] = (left, right)
    for r, reg in enumerate(registers):
        own = [v for v in vigs if v["reg"] == r]
        if not own:
            continue
        text = [u for u in reg["units"] if u["kind"] != "vignette"]
        nat = [unit_fit(u, glyphs, Qs[r])[0] + GUTTER * Qs[r] for u in text]
        room = (x1 - x0) - sum(v["w"] + 2 * VIG_GAP * Q for v in own)
        f = room / max(1.0, sum(nat))
        x, ti = x1, 0
        for i, u in enumerate(reg["units"]):
            if u["kind"] == "vignette":
                v = next(v for v in own if v["index"] == i)
                x -= VIG_GAP * Q
                v["x1"], v["x0"] = x, x - v["w"]
                x -= v["w"] + VIG_GAP * Q
            else:
                x -= nat[ti] * f
                ti += 1
    placed, ovals = [], []
    for r, reg in enumerate(registers):
        top, bot = regs[r]
        cuts = [(v["x0"] - VIG_GAP * Q, v["x1"] + VIG_GAP * Q) for v in vigs if v["rows"][0] <= r <= v["rows"][1]]
        segs = subtract(blocks.get(r, (x0, x1)), cuts)
        own = sorted([v for v in vigs if v["reg"] == r], key=lambda v: v["index"])
        text = [u for u in reg["units"] if u["kind"] != "vignette"]
        # The register's own vignettes split its text: what precedes one runs right of it.
        bounds_x = [x1] + [c for v in own for c in (v["x1"] + VIG_GAP * Q, v["x0"] - VIG_GAP * Q)] + [x0]
        cut_at = []
        k = 0
        for i, u in enumerate(reg["units"]):
            if u["kind"] == "vignette":
                cut_at.append(k)
            else:
                k += 1
        pieces = [text[a:b] for a, b in zip([0] + cut_at, cut_at + [len(text)])]
        for j, piece in enumerate(pieces):
            hi, lo = bounds_x[2 * j], bounds_x[2 * j + 1]
            sub = [(max(a, lo), min(b, hi)) for a, b in segs if min(b, hi) - max(a, lo) > 1]
            for u, info, xr, s, m in pack(piece, sub, glyphs, Qs[r], GROW_MAX):
                Qu = Qs[r] * s
                mid = (top + bot) / 2
                if u["kind"] == "quadrat":
                    w = unit_fit(u, glyphs, Qu, m)[0]
                    ytop = mid - info["h"] / 2
                    placed += [dict(sign=sg, k=kk, x=xr - w + ix, y=ytop + iy) for sg, kk, ix, iy in info["items"]]
                else:
                    w = unit_fit(u, glyphs, Qu, m)[0]
                    ch = info["ch"]
                    ovals.append((xr - w, mid - ch / 2, xr, mid + ch / 2))
                    ix = xr - ch * 0.26 - 0.03 * Qu
                    for iw, ih, items in info["inner"]:
                        placed += [dict(sign=sg, k=kk, x=ix - iw + jx, y=mid - ih / 2 + jy) for sg, kk, jx, jy in items]
                        ix -= iw + info["igap"]
    boxes = []
    for v in vigs:
        placed += [dict(sign=sg, k=kk, x=v["x0"] + ix, y=v["top"] + iy) for sg, kk, ix, iy in v["items"]]
        boxes.append((v["x0"], v["top"], v["x1"], v["top"] + v["h"], v["rows"][0], v["rows"][1]))
    rule_spans = {r: blocks[r] for r in blocks if r + 1 in blocks and blocks[r + 1] == blocks[r]}
    return Q, (regs, bands, rules, fill, rule_spans), placed, ovals, boxes


