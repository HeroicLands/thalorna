def region_colours(sign, labels, n, ink_bin, pos_index):
    """A colour for each enclosed region of a sign, by its colour's convention."""
    cat = sign["colour"]
    ys, xs = np.nonzero(ink_bin)
    top, span = ys.min(), max(1, ys.max() - ys.min())
    left, wspan = xs.min(), max(1, xs.max() - xs.min())
    upright = span > 0.8 * wspan  # a person, not a mouth or a lip
    head = ink_bin[top:top + max(1, int(0.12 * span))]
    head_cx = (np.nonzero(head)[1].mean() - left) / wspan if head.any() else 0.5
    objs = ndimage.find_objects(labels)
    areas = ndimage.sum_labels(np.ones_like(labels), labels, index=np.arange(1, n + 1)) if n else []
    largest = max(areas) if n else 1
    tone = sign.get("tone")
    bird_a = PIG["green"] if tone == "green" or (tone is None and pos_index % 2) else PIG["blue"]
    bird_b = PIG["blue"] if bird_a == PIG["green"] else PIG["green"]
    colours = {}
    order = sorted(range(n), key=lambda i: objs[i][1].start if objs[i] else 0)
    for rank, i in enumerate(order):
        sl = objs[i]
        if sl is None:
            continue
        rh, rw = sl[0].stop - sl[0].start, sl[1].stop - sl[1].start
        rel_top, rel_bot = (sl[0].start - top) / span, (sl[0].stop - top) / span
        rel_cx = ((sl[1].start + sl[1].stop) / 2 - left) / wspan
        frac = areas[i] / largest
        long_thin = max(rh, rw) > 3.2 * min(rh, rw)
        if cat == "gold":
            c = GOLD
        elif cat == "figure":
            if rel_top < 0.06 and rel_bot < 0.32 and rw > rh * 0.5:
                c = PIG["black"]  # the wig
            elif (upright and KILT_BAND[0] <= rel_top <= KILT_BAND[1] and KILT_HEM[0] <= rel_bot <= KILT_HEM[1]
                  and rw >= 0.08 * span and rw >= 0.35 * rh and abs(rel_cx - head_cx) < 0.25):
                c = PIG["white"]  # a standing figure's kilt, from the belt to the hem
            elif upright and rel_top > 0.40 and rw > rh * 0.45 and frac > 0.25 and rel_bot > 0.7:
                c = PIG["white"]  # kilt and long garment
            else:
                c = PIG["red"]
        elif cat == "bird":
            if rel_top > 0.62 and rw < rh * 1.6:
                c = PIG["red"]  # legs
            elif rel_bot < 0.42 and frac < 0.8:
                c = bird_b  # the head
            else:
                c = bird_a
        elif cat == "plant":
            c = PIG["green"] if (rank % 2 == 0 or n < 5) else PIG["blue"]
        elif cat == "water":
            c = PIG["blue"]
        elif cat == "land":
            c = PIG["land"]
        elif cat == "stroke":
            c = PIG["blueblack"]
        elif cat == "god:uqaa":
            c = PIG["red"] if frac < 0.6 else GOLD
        elif cat == "god:uznera":
            c = PIG["red"] if long_thin and frac < 0.5 else (PIG["white"] if rel_bot < 0.55 else PIG["green"])
        elif cat == "god:qearet":
            c = PIG["white"] if rel_bot < 0.55 else GOLD
        elif cat == "god:rethsaar":
            c = GOLD if frac > 0.6 else (PIG["turquoise"] if long_thin else PIG["red"])
        elif cat == "god:chaqur":
            c = GOLD if (abs(rel_cx - 0.5) < 0.2 and rh > 2.5 * rw) else PIG["green"]
        else:  # object
            c = PIG["yellow"] if frac >= 0.28 else PIG["red"]
        colours[i + 1] = c
    return colours


def disk(r):
    yy, xx = np.mgrid[-r:r + 1, -r:r + 1]
    return (xx * xx + yy * yy) <= r * r


def paint_sign(glyphs, sign, k, pos_index):
    """One sign as tile layers: silhouette coverage, paint colour, gold weight and interior
    grooves, mirrored when the sign's flag asks."""
    close = PAINT["signs"].get(sign["id"], {}).get("close", ())
    regions = PAINTMOD.Regions(glyphs.pg, sign["glyph"], k, close=close)
    cov, ink_bin, hair, pad = regions.coverage.astype(np.float32), regions.ink, regions.hair, regions.pad
    lab2, n2 = regions.labels.copy(), regions.n
    # The painted outline is finer than the drawn hairline: the line's core, about 0.8 of it.
    core = ndimage.distance_transform_edt(np.pad(ink_bin, 1))[1:-1, 1:-1]
    ink_paint = np.clip(core - OUTLINE_TRIM * hair + 0.5, 0, 1).astype(np.float32)
    mapped = sign["id"] in PAINT["signs"]
    if mapped:
        names = PAINTMOD.paints(PAINT, sign["id"], regions)
        # negative space (air between a bow and its string, inside a loop) is bare wall
        for i, name in names.items():
            if name == "ground":
                lab2[lab2 == i] = 0
        cols = {i: (GOLD if nm == "gold" else CATEGORY_COLOURS[nm]) for i, nm in names.items() if nm != "ground"}
    inside = lab2 > 0
    if not mapped:
        cols = region_colours(sign, lab2, n2, ink_bin, pos_index)
    overrides = [] if mapped else SIGN_REGIONS.get(sign["id"], [])
    if overrides and n2:
        r = max(2, int(math.ceil(hair * 1.15)))
        ys, xs = np.nonzero(ink_bin)
        for fx, fy, name in overrides:
            py = int(round(ys.min() + fy * (ys.max() - ys.min())))
            px = int(round(xs.min() + fx * (xs.max() - xs.min())))
            win = lab2[max(0, py - r * 2):py + r * 2 + 1, max(0, px - r * 2):px + r * 2 + 1]
            hit = lab2[py, px] if lab2[py, px] else (np.bincount(win[win > 0]).argmax() if (win > 0).any() else 0)
            if hit:
                cols[int(hit)] = GOLD if name == "gold" else PIG[name]

    hh, ww = cov.shape
    colour = np.zeros((hh, ww, 3), np.float32)
    gold = np.zeros((hh, ww), np.float32)
    for i, c in cols.items():
        m = lab2 == i
        if c == GOLD:
            gold[m] = 1.0
            colour[m] = GOLD_FLAT
        elif c == PIG["white"] and sign["colour"] == "figure" and not mapped:
            # A kilt's outline often closes on the legs, so the white region runs to the feet.
            # The kilt is the broad part; legs and feet are narrow, so a disc wider than a leg
            # keeps the kilt to its hem and the limbs below take the skin colour.
            r = max(2, int(math.ceil(hair * KILT_DISC)))
            kilt = ndimage.binary_opening(m, structure=disk(r))
            kilt = ndimage.binary_dilation(kilt, iterations=max(1, r // 3)) & m
            colour[m] = PIG["red"]
            if kilt.sum() >= 0.15 * m.sum():
                colour[kilt] = PIG["white"]
        else:
            colour[m] = c
    cat = sign["colour"]
    if cat == "land":
        # red dots on the pink-brown ground
        rng = np.random.default_rng(int(sign["id"].replace("-", "")) + pos_index)
        dots = np.zeros_like(inside)
        step = max(4, int(hair * 2.2))
        for y in range(step // 2, hh, step):
            for x in range((y // step % 2) * step // 2, ww, step):
                jx, jy = rng.integers(-1, 2, 2)
                yy, xx = y + jy, x + jx
                if 0 <= yy < hh and 0 <= xx < ww:
                    dots[yy, xx] = True
        dots = ndimage.binary_dilation(dots, structure=disk(max(1, int(hair * 0.35)))) & ndimage.binary_erosion(inside, iterations=max(1, int(hair * 0.4)))
        colour[dots] = PIG["red"]
    sil = np.maximum(cov, inside.astype(np.float32))
    # Solid ink (a pupil, a knot, a sun's disk) is wider than the hairline.
    solid = ndimage.binary_opening(ink_bin, structure=disk(int(math.ceil(hair * 0.9))))
    solid_big = solid.sum() > 0.03 * max(1.0, float(sil.sum()))
    water_lines = cat == "water" and inside.sum() < 0.15 * sil.sum()
    if cat in ("gold", "god:uqaa", "god:qearet", "god:rethsaar", "god:chaqur", "god:uznera"):
        line = PIG["gold_ink"] if cat == "gold" else PIG["ink"]
    elif cat == "stroke":
        line = PIG["blueblack"]
    elif water_lines:
        line = PIG["blue"]
    else:
        line = PIG["ink"]
    if cat == "god:uqaa":
        line = PIG["red_dark"]  # the flame tongues are drawn in line
    outline = PAINT["signs"][sign["id"]].get("outline") if mapped else None
    if outline and outline != "default":
        line = tuple(c * 0.45 for c in (GOLD_FLAT if outline == "gold" else CATEGORY_COLOURS[outline]))
    # Under the trimmed edges of the line, the fill beside it runs on; a line with no fill
    # beside it (a staff, a cord) keeps its colour.
    if n2:
        dist, idx = ndimage.distance_transform_edt(lab2 == 0, return_indices=True)
        near = ink_bin & (dist <= 1.5 * hair)
        colour[near] = colour[idx[0][near], idx[1][near]]
        gold[near] = gold[idx[0][near], idx[1][near]]
        far = ink_bin & ~near
        colour[far] = line
    else:
        colour[ink_bin] = line
    a = ink_paint[..., None]
    colour = colour * (1 - a) + np.array(line, np.float32) * a
    gold *= 1 - ink_paint
    if solid.any() and (cat == "gold" or cat == "god:uqaa") and solid_big:
        gold = np.maximum(gold, solid.astype(np.float32))
        colour[solid] = GOLD_FLAT
    elif solid.any() and water_lines:
        colour[solid] = PIG["blue"]
    sil = np.maximum(sil, cov)
    grooves = cov * ndimage.binary_dilation(inside, iterations=2) * (~solid)
    layers = dict(sil=sil, colour=colour, gold=gold, grooves=grooves.astype(np.float32))
    if sign["mirror"]:
        layers = {key: np.ascontiguousarray(v[:, ::-1]) for key, v in layers.items()}
    return layers, pad


