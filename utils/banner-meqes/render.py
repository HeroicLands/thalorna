class Scene:
    def __init__(self, ss):
        self.ss = ss
        self.h, self.w = H * ss, W * ss
        self.rng = np.random.default_rng(SEED)
        self.rgb = np.zeros((self.h, self.w, 3), np.float32)
        self.height = np.zeros((self.h, self.w), np.float32)  # relief height of the raised work
        self.gold = np.zeros((self.h, self.w), np.float32)
        self.ovals, self.vignettes = [], []
        self.sil = np.zeros((self.h, self.w), np.float32)  # the raised work, for occlusion and measuring
        self.plaster = np.zeros((self.h, self.w), np.float32)

    def S(self, v):
        return int(round(v * self.ss))

    # The wall, the bands and the dado ------------------------------------------------------

    def wall(self, frame, vignettes):
        """The gypsum ground, the episode bands, the thin rules and the dado."""
        s = self.ss
        regs, bands, rules = frame[:3]
        g = np.array(PIG["ground"], np.float32)
        self.tex = fbm((self.h, self.w), self.rng, [(0.5 * s, 0.006), (2.0 * s, 0.006), (12 * s, 0.006), (90 * s, 0.020)])
        self.rgb[:] = g * (1 + self.tex[..., None])
        # the plaster's own surface: fine grain and a very slight unevenness, lit with the relief
        self.plaster = fbm((self.h, self.w), self.rng, [(0.6 * s, 0.005), (2.5 * s, 0.005), (40 * s, 0.06)])
        # hand-laid paint: tone varies a little along the brush
        self.brush = fbm((self.h, self.w), self.rng, [(1.5 * s, 0.012), ((1.2 * s, 14 * s), 0.035), (25 * s, 0.03)])
        x0, x1 = self.S(BAND_X0), self.S(BAND_X1)
        for y, ci in bands:
            name = BAND_COLOURS[ci % len(BAND_COLOURS)]
            y0, y1 = self.S(y), self.S(y + BAND)
            self.paint_band(y0, y1, x0, x1, name)
        for y, ci, upper in rules:
            name = BAND_COLOURS[ci % len(BAND_COLOURS)]
            y0, y1 = self.S(y), max(self.S(y) + 1, self.S(y + RULE))
            if upper in frame[4]:
                a, b = frame[4][upper]
                self.paint_band(y0, y1, self.S(a), self.S(b), name, dark=True)
                continue
            cuts = []
            for v in vignettes:
                if v[4] <= upper < v[5]:
                    c0 = BAND_X0 if v[0] <= WALL_X0 + 1 else v[0] - 0.05 * self.Q
                    c1 = BAND_X1 if v[2] >= WALL_X1 - 1 else v[2] + 0.05 * self.Q
                    cuts.append((self.S(c0), self.S(c1)))
            for a, b in subtract((x0, x1), cuts):
                self.paint_band(y0, y1, int(a), int(b), name, dark=True)
        d0 = self.S(DADO)
        self.rgb[d0:d0 + self.S(2.5)] = PIG["black"]
        self.rgb[d0 + self.S(2.5):d0 + self.S(7)] = PIG["yellow"]
        self.rgb[d0 + self.S(7):d0 + self.S(9.5)] = PIG["black"]
        lo = d0 + self.S(9.5)
        self.rgb[lo:] = np.array(PIG["dado"], np.float32) * (1 + 0.6 * self.tex[lo:, :, None] + self.brush[lo:, :, None])
        self.rgb[d0:lo] *= 1 + self.brush[d0:lo, :, None]
        f0 = self.S(H - 5)
        self.rgb[f0:] = np.array(PIG["dado"], np.float32) * 0.5

    def paint_band(self, y0, y1, x0, x1, name, dark=False):
        b = self.brush[y0:y1, x0:x1, None]
        if name == "gold":
            self.gold[y0:y1, x0:x1] = 1.0
            self.height[y0:y1, x0:x1] += 0.10
            c = np.array(GOLD_FLAT, np.float32) * (0.62 if dark else 1.0)
            if dark:
                self.gold[y0:y1, x0:x1] = 0.0
        else:
            c = np.array(PIG[name], np.float32) * (0.68 if dark else 1.0)
        self.rgb[y0:y1, x0:x1] = c * (1 + b + 0.5 * self.tex[y0:y1, x0:x1, None])

    def kheker(self):
        """A row of kheker ornaments: a tied sheaf with a knob, banded red, blue and green with
        white ties, painted flat on the wall's head."""
        s = self.ss
        y0, y1 = KHEKER
        pitch, wdt = 22, 14
        layer = Image.new("RGB", (self.w, self.S(y1 - y0)), (0, 0, 0))
        alpha = Image.new("L", (self.w, self.S(y1 - y0)), 0)
        d, da = ImageDraw.Draw(layer), ImageDraw.Draw(alpha)
        hgt = (y1 - y0) - 4
        lw = max(1, int(round(s * 0.9)))

        def P(px, py):
            return (px * s, py * s)

        colours = [PIG["red"], PIG["blue"], PIG["green"]]
        x, i = BAND_X0 - pitch, 0
        while x < BAND_X1 + pitch:
            cx = x + pitch / 2
            c = colours[i % 3]
            top = 2
            kr = wdt * 0.34
            body = [
                P(cx - wdt * 0.18, top + kr * 1.7), P(cx + wdt * 0.18, top + kr * 1.7),
                P(cx + wdt * 0.50, top + hgt * 0.32), P(cx + wdt * 0.50, top + hgt * 0.90),
                P(cx + wdt * 0.36, top + hgt), P(cx - wdt * 0.36, top + hgt),
                P(cx - wdt * 0.50, top + hgt * 0.90), P(cx - wdt * 0.50, top + hgt * 0.32),
            ]
            knob = [P(cx - kr, top), P(cx + kr, top + 2 * kr)]
            da.polygon(body, fill=255)
            da.ellipse(knob, fill=255)
            d.polygon(body, fill=c)
            d.ellipse(knob, fill=PIG["yellow"])
            for f in (0.34, 0.58):
                ty = top + hgt * f
                d.rectangle([P(cx - wdt * 0.5, ty), P(cx + wdt * 0.5, ty + 2.4)], fill=PIG["white"], outline=PIG["black"], width=lw)
            d.line(body + [body[0]], fill=PIG["black"], width=lw)
            d.ellipse(knob, outline=PIG["black"], width=lw)
            x += pitch
            i += 1
        a = np.asarray(alpha, np.float32)[..., None] / 255.0
        lay = np.asarray(layer, np.float32) * (1 + 0.5 * self.tex[self.S(y0):self.S(y1), :, None])
        ys = slice(self.S(y0), self.S(y1))
        self.rgb[ys] = self.rgb[ys] * (1 - a) + lay * a * (1 + self.brush[ys, :, None])
        # the frieze is carved in low relief
        self.height[ys] += 0.7 * ndimage.gaussian_filter(a[..., 0], 0.8 * s)
        self.sil[ys] = np.maximum(self.sil[ys], a[..., 0])
        b = self.S(y1)
        self.rgb[b:b + self.S(1.5), self.S(BAND_X0):self.S(BAND_X1)] = PIG["black"]

    # Signs ---------------------------------------------------------------------------------

    def signs(self, glyphs, placed, ovals):
        for box in ovals:
            self.oval(box)
        for n, p in enumerate(placed):
            self.put_sign(glyphs, p, n)

    def put_sign(self, glyphs, p, n):
        ss = self.ss
        layers, pad = paint_sign(glyphs, p["sign"], p["k"] * ss, n)
        x0 = int(round(p["x"] * ss)) - pad
        y0 = int(round(p["y"] * ss)) - pad
        hh, ww = layers["sil"].shape
        ys, xs = slice(y0, y0 + hh), slice(x0, x0 + ww)
        sil = layers["sil"]
        a = sil[..., None]
        paint = layers["colour"] * (1 + self.brush[ys, xs, None])
        self.rgb[ys, xs] = self.rgb[ys, xs] * (1 - a) + paint * a
        self.sil[ys, xs] = np.maximum(self.sil[ys, xs], sil)
        self.gold[ys, xs] = np.maximum(self.gold[ys, xs] * (1 - sil), layers["gold"])
        self.height[ys, xs] = np.maximum(self.height[ys, xs], self.relief(sil, layers["grooves"]))

    def relief(self, sil, grooves):
        """Raised, rounded at the edge, gently domed, with the drawing's interior lines modelled
        as shallow grooves."""
        ss = self.ss
        inside = sil > 0.5
        d = ndimage.distance_transform_edt(inside).astype(np.float32)
        hgt = np.clip(d / (1.5 * ss), 0, 1)
        hgt = hgt * hgt * (3 - 2 * hgt)
        dome = ndimage.gaussian_filter(inside.astype(np.float32), 4 * ss)
        hgt = hgt * (0.80 + 0.35 * dome)
        hgt -= 0.20 * ndimage.gaussian_filter(grooves, 0.5 * ss)
        hgt = ndimage.gaussian_filter(hgt, 0.4 * ss)
        return np.clip(hgt, 0, None) * sil

    def oval(self, box):
        """The cord oval in gold leaf, raised and twisted, with its tie bar at the left."""
        ss = self.ss
        x0, y0, x1, y1 = box
        cw = 0.085 * self.Q * ss
        X0, Y0, X1, Y1 = (int(v * ss) for v in (x0 - 4, y0 - 6, x1 + 4, y1 + 6))
        shape = (Y1 - Y0, X1 - X0)
        ox, oy = x0 * ss - X0, y0 * ss - Y0
        w, h = (x1 - x0) * ss, (y1 - y0) * ss
        bar = cw * 1.05
        sd = stadium_dist(shape, ox + bar * 0.7, oy, ox + w, oy + h)
        ring_d = cw / 2 - np.abs(sd - cw / 2)  # distance inside the band of the cord
        ring = np.clip(ring_d + 0.5, 0, 1)
        yy, xx = np.mgrid[0:shape[0], 0:shape[1]].astype(np.float32)
        bar_d = np.minimum(np.minimum(xx - ox, ox + bar - xx), np.minimum(yy - (oy - 0.06 * h), oy + 1.06 * h - yy))
        barm = np.clip(bar_d + 0.5, 0, 1)
        cord = np.maximum(ring, barm)
        dist = np.maximum(np.where(ring > 0, ring_d, 0), np.where(barm > 0, np.minimum(bar_d, bar / 2), 0))
        # the twist: shallow grooves slanting across the cord
        theta = np.arctan2(yy - (oy + h / 2), (xx - (ox + w / 2)) * (h / w))
        twist = np.sin(theta * 64 + sd * 0.15)
        hgt = np.sqrt(np.clip(dist / (cw * 0.5), 0, 1)) * (0.9 + 0.1 * twist * (ring > 0)) * cord
        line = np.clip(cord - np.clip((dist - 0.7 * ss) / (0.6 * ss), 0, 1), 0, 1) * 0.8
        ys, xs = slice(Y0, Y1), slice(X0, X1)
        a = cord[..., None]
        col = np.array(GOLD_FLAT, np.float32) * (1 - line[..., None]) + np.array(PIG["gold_ink"], np.float32) * line[..., None]
        self.rgb[ys, xs] = self.rgb[ys, xs] * (1 - a) + col * a
        self.gold[ys, xs] = np.maximum(self.gold[ys, xs], cord * (1 - line))
        self.sil[ys, xs] = np.maximum(self.sil[ys, xs], cord)
        self.height[ys, xs] = np.maximum(self.height[ys, xs], ndimage.gaussian_filter(hgt, 0.4 * ss))

    # Light ---------------------------------------------------------------------------------

    def light_relief(self):
        """Light everything by its normals from the upper left: the relief's lit and shadowed
        edges, the plaster's grain, the soft cast shadows, ambient occlusion where the relief meets
        the ground, and the gold leaf's metal."""
        ss = self.ss
        hgt = self.height

        def facing(h):
            gy, gx = np.gradient(h * 3.0 * ss)
            norm = np.sqrt(gx * gx + gy * gy + 1)
            nx, ny, nz = -gx / norm, -gy / norm, 1 / norm
            return nx, ny, nz, nx * LIGHT[0] + ny * LIGHT[1] + nz * LIGHT[2]

        flat = LIGHT[2]
        # paint and plaster take the plaster's grain; burnished gold leaf is smooth
        lam_p = facing(hgt + self.plaster)[3]
        nx, ny, nz, lam = facing(hgt)
        shade = 1.0 + 1.35 * (lam_p - flat)
        raised = np.clip(self.sil, 0, 1)
        rh = hgt * raised
        foot = np.clip(rh * 4, 0, 1)
        sh = ndimage.shift(foot, (2.4 * ss, 2.0 * ss), order=1)
        sh = ndimage.gaussian_filter(sh, 1.4 * ss)
        cast = 1 - 0.40 * sh * (1 - foot)
        occ = np.clip(ndimage.gaussian_filter(foot, 3.0 * ss) - foot, 0, 1)
        ao = 1 - 0.45 * occ
        light = np.clip(shade, 0.3, 1.8) * cast * ao
        rgb = self.rgb * light[..., None]
        g = self.gold
        broad = ndimage.gaussian_filter(rh, 5 * ss)
        by, bx = np.gradient(broad * 16 * ss)
        bl = -bx * LIGHT[0] - by * LIGHT[1]
        env = fbm((self.h, self.w), np.random.default_rng(SEED + 7), [(8 * ss, 0.03), (30 * ss, 0.04)])
        t = 0.58 + 1.8 * (lam - flat) + 0.8 * bl + env
        metal = gold_from(t)
        hv = LIGHT + np.array([0, 0, 1.0])
        hv /= np.linalg.norm(hv)
        spec = np.clip(nx * hv[0] + ny * hv[1] + nz * hv[2], 0, 1) ** 90 * np.clip(1 + 3 * env, 0, 2)
        glint = 0.6 * spec + 0.7 * np.clip(lam - flat, 0, 1) ** 1.4
        metal += np.array([255, 246, 214], np.float32) * glint[..., None] * 0.75
        metal *= (cast * ao)[..., None]
        self.rgb = rgb * (1 - g[..., None]) + metal * g[..., None]
        self.glow = np.clip((spec + glint) * g - 0.3, 0, None)

    def ceiling(self):
        s = self.ss
        y0, y1 = (self.S(v) for v in CEIL)
        t = np.linspace(0, 1, y1 - y0, dtype=np.float32)[:, None, None]
        tex = fbm((y1 - y0, self.w), self.rng, [(0.6 * s, 0.015), (20 * s, 0.03)])
        self.rgb[y0:y1] = np.array(PIG["ceiling"], np.float32) * (0.78 + 0.28 * t) * (1 + tex[..., None])
        polys = []
        pitch = 40
        for row, cy in enumerate((9, 25)):
            for j in range(-1, W // pitch + 2):
                polys.append(star_points(j * pitch + (pitch / 2 if row else 0) + 8, cy, 6.6))
        m = ndimage.gaussian_filter(poly_mask((y1 - y0, self.w), polys, s), 0.3 * s)
        star = np.array(PIG["star"], np.float32) * (1 + tex[..., None])
        self.rgb[y0:y1] = self.rgb[y0:y1] * (1 - m[..., None]) + star * m[..., None]
        # the ceiling meets the beam in a dark line
        self.rgb[y1 - self.S(1.5):y1] *= 0.55

    def architrave(self):
        s = self.ss
        y0, y1 = (self.S(v) for v in ARCH)
        tex = fbm((y1 - y0, self.w), self.rng, [(0.5 * s, 0.008), (30 * s, 0.015)])
        self.rgb[y0:y1] = np.array(PIG["ground"], np.float32) * 0.98 * (1 + tex[..., None])
        self.rgb[y0:y0 + self.S(1.5)] *= 1.07  # the beam's top arris catches the light
        b0, b1 = ARCH[0] + 9, ARCH[1] - 9
        Y0, Y1 = self.S(b0), self.S(b1)
        self.rgb[Y0 - self.S(1.5):Y0] = PIG["black"]
        self.rgb[Y1:Y1 + self.S(1.5)] = PIG["black"]
        seq = [PIG["blue"], PIG["red"], PIG["green"], PIG["yellow"]]
        bw, x, i = 16, 0, 0
        while x < W:
            self.rgb[Y0:Y1, self.S(x):self.S(x + bw - 3)] = seq[i % 4]
            self.rgb[Y0:Y1, self.S(x + bw - 3):self.S(x + bw - 1.3)] = PIG["white"]
            self.rgb[Y0:Y1, self.S(x + bw - 1.3):self.S(x + bw)] = PIG["black"]
            x += bw
            i += 1
        a0, a1 = (self.S(v) for v in SOFFIT)
        grad = np.linspace(0.36, 0.5, a1 - a0, dtype=np.float32)[:, None, None]
        self.rgb[a0:a1] = np.array(PIG["ground"], np.float32) * grad

    def column(self, axis, side):
        """A papyrus-bundle column: a rounded shaft of stems, banded at the neck under a
        closed-bud capital that carries the architrave."""
        s = self.ss
        top, bot = SOFFIT[0], H
        R = COL_R0
        cap_top, cap_bot = top + 6, top + 66
        neck0, neck1 = cap_bot, cap_bot + 28
        Hh, Ww = self.S(bot - top), self.S(2 * R + 60)
        yy, xx = np.mgrid[0:Hh, 0:Ww].astype(np.float32)
        yy = yy / s + top
        xx = xx / s + axis - R - 30
        t = np.clip((yy - cap_top) / (cap_bot - cap_top), 0, 1)
        cap_r = R * (0.80 + 0.36 * np.sin(np.pi * (0.18 + 0.82 * t)))
        r = np.where(yy < cap_bot, cap_r, R * (1.0 - 0.035 * (yy - neck1) / (bot - neck1)))
        u = (xx - axis) / r
        inside = np.clip((1 - np.abs(u)) * r * s * 0.5, 0, 1)
        uc = np.clip(u, -1, 1)
        nzc = np.sqrt(1 - uc * uc)
        lam = np.clip(-uc * 0.70 + nzc * 0.72, 0, 1.2)
        shade = 0.40 + 0.80 * lam
        stems = 7
        phase = (np.arcsin(uc) / np.pi + 0.5) * stems
        ridge = np.abs(np.sin(phase * np.pi))
        shade = shade * (0.66 + 0.34 * ridge ** 0.7)  # each stem rounds into a dark flute
        shade = shade * (0.55 + 0.45 * nzc ** 0.35)  # occlusion where the shaft turns from view
        sheen = 0.16 * np.clip(-uc * 0.55 + nzc * 0.83, 0, 1) ** 24 * ridge
        base = np.array(PIG["ground"], np.float32)
        col = np.broadcast_to(base, yy.shape + (3,)).copy()
        # stems painted in yellow ochre with green lines between them
        col[:] = np.array((226, 196, 136), np.float32)
        between = np.clip(1 - ridge / 0.18, 0, 1) * (yy > neck1)
        col = col * (1 - between[..., None]) + np.array(PIG["green"], np.float32) * between[..., None]
        bands = [PIG["blue"], PIG["white"], PIG["red"], PIG["white"], PIG["green"], PIG["white"], PIG["blue"]]
        bh = (neck1 - neck0) / len(bands)
        for i, c in enumerate(bands):
            col[(yy >= neck0 + i * bh) & (yy < neck0 + (i + 1) * bh)] = c
            col[(yy >= neck0 + (i + 1) * bh - 0.7) & (yy < neck0 + (i + 1) * bh)] = PIG["black"]
        f0 = DADO + 4
        for i, c in enumerate([PIG["red"], PIG["white"], PIG["blue"], PIG["white"], PIG["red"]]):
            col[(yy >= f0 + i * 4.4) & (yy < f0 + (i + 1) * 4.4)] = c
        # the capital: pointed sepals in green and blue over a yellow ground
        capm = yy < cap_bot
        petal = (np.arcsin(uc) / np.pi + 0.5) * 6
        pv = (yy - cap_top) / (cap_bot - cap_top)
        frac = np.abs(np.sin(petal * np.pi))
        lim = np.clip((1 - pv) * 1.05, 0, 1)
        pet = frac > lim
        green_blue = np.where((np.floor(petal) % 2 == 0)[..., None], np.array(PIG["green"], np.float32), np.array(PIG["blue"], np.float32))
        capc = np.where(pet[..., None], green_blue, np.array(PIG["yellow"], np.float32))
        capc[np.abs(frac - lim) < 0.05] = PIG["black"]
        col[capm] = capc[capm]
        ab = yy < cap_top
        col[ab] = base * 0.96
        alpha = np.where(ab, (np.abs(xx - axis) <= R * 0.74).astype(np.float32), inside)
        tex = fbm(yy.shape, self.rng, [(0.5 * s, 0.008), (8 * s, 0.008)])
        rgb = col * shade[..., None] * (1 + tex[..., None]) + 255 * sheen[..., None]
        under = 1 - 0.45 * np.exp(-np.clip(yy - SOFFIT[1], 0, None) / 14) * (yy > cap_top)
        rgb *= under[..., None]
        # the shaft's soft shadow on the wall, away from the light
        Y0 = self.S(top)
        if side == "left":
            sx, w_ = self.S(axis + R - 2), self.S(52)
            ramp = np.linspace(0.70, 1.0, w_, dtype=np.float32) ** 1.3
            self.rgb[self.S(SOFFIT[1]):, sx:sx + w_] *= ramp[None, :, None]
        else:
            sx, w_ = self.S(axis - R + 2), self.S(14)
            ramp = np.linspace(1.0, 0.84, w_, dtype=np.float32)
            self.rgb[self.S(SOFFIT[1]):, sx - w_:sx] *= ramp[None, :, None]
        X0 = self.S(axis - R - 30)
        x_lo, x_hi = max(0, X0), min(self.w, X0 + Ww)
        cs = slice(x_lo - X0, x_hi - X0)
        a = alpha[:, cs][..., None]
        self.rgb[Y0:Y0 + Hh, x_lo:x_hi] = self.rgb[Y0:Y0 + Hh, x_lo:x_hi] * (1 - a) + rgb[:, cs] * a

    def ambient(self):
        """Warm interior light falling off from the upper left, and the architrave's shadow on
        the frieze and the wall's head."""
        yy, xx = np.mgrid[0:self.h, 0:self.w].astype(np.float32)
        yy /= self.h
        xx /= self.w
        d = np.sqrt((xx + 0.05) ** 2 + (yy * 1.15 + 0.1) ** 2)
        lit = 1.16 - 0.40 * np.clip(d, 0, 1.6) ** 1.25
        warm = np.stack([lit * 1.02, lit * 0.985, lit * 0.94], -1)
        py = yy * H
        below = py - SOFFIT[1]
        under = 1 - (0.42 * np.exp(-np.clip(below, 0, None) / 6) + 0.18 * np.exp(-np.clip(below, 0, None) / 30)) * (below > 0)
        # the ceiling is recessed above the beam and darker
        under = np.where(py < CEIL[1], under * 0.82, under)
        self.rgb *= warm * under[..., None]

    def camera(self, img):
        """A photograph's finish: warm white balance, a gentle tone curve, a soft bloom on the
        gold, a slight vignette and fine grain."""
        a = np.asarray(img, np.float32) / 255.0
        glow = Image.fromarray(np.clip(self.glow * 255, 0, 255).astype(np.uint8)).resize((W, H), Image.LANCZOS)
        g = ndimage.gaussian_filter(np.asarray(glow, np.float32) / 255.0, 2.5)
        a += 0.22 * g[..., None] * np.array([1.0, 0.85, 0.55])
        a *= np.array([1.035, 1.0, 0.91])
        a = np.clip(a, 0, 1)
        a = a + 0.22 * (a * a * (3 - 2 * a) - a)  # a soft S curve
        yy, xx = np.mgrid[0:H, 0:W].astype(np.float32)
        r = np.sqrt(((xx - W / 2) / (W / 2)) ** 2 + ((yy - H / 2) / (H / 2)) ** 2) / math.sqrt(2)
        a *= (1 - 0.20 * r ** 2.2)[..., None]
        grain = np.random.default_rng(SEED + 3).standard_normal((H, W)).astype(np.float32)
        grain = ndimage.gaussian_filter(grain, 0.6) * 0.010
        a += grain[..., None]
        return Image.fromarray(np.clip(a * 255 + 0.5, 0, 255).astype(np.uint8))

    def finish(self):
        img = Image.fromarray(np.clip(self.rgb, 0, 255).astype(np.uint8))
        return self.camera(img.resize((W, H), Image.LANCZOS))

def render(glyphs, registers, scenes, ss, empty=False):
    sc = Scene(ss)
    Q, frm, placed, ovals, vigs = layout(registers, glyphs, scenes)
    sc.Q, sc.frame, sc.vignettes, sc.ovals = Q, frm, vigs, ovals
    sc.wall(frm, vigs if not empty else [])
    sc.kheker()
    if not empty:
        sc.signs(glyphs, placed, ovals)
    sc.ceiling()
    sc.architrave()
    sc.light_relief()
    sc.ambient()
    sc.column(COL_L, "left")
    sc.column(COL_R, "right")
    return sc


def density(sil, regs, vignettes):
    """Per register: the gaps between neighbouring ink (runs of bare columns between the first
    and last inked column, vignettes left out) and the share of the register that is bare ground."""
    out = []
    for r, (top, bot) in enumerate(regs):
        strip = sil[int(round(top)):int(round(bot)), WALL_X0:WALL_X1] > 0.35
        cols = strip.any(axis=0)
        for v in vignettes:
            if v[4] <= r <= v[5]:
                cols[max(0, int(v[0]) - WALL_X0):max(0, int(v[2]) - WALL_X0)] = True
        idx = np.nonzero(cols)[0]
        gaps = []
        if len(idx):
            run = 0
            for c in cols[idx[0]:idx[-1] + 1]:
                if c:
                    if run:
                        gaps.append(run)
                    run = 0
                else:
                    run += 1
        out.append(dict(mean_gap=float(np.mean(gaps)) if gaps else 0.0, max_gap=max(gaps) if gaps else 0,
                        bare=float(1 - strip.mean()), lead=int(idx[0]) if len(idx) else 0,
                        tail=int(strip.shape[1] - 1 - idx[-1]) if len(idx) else 0))
    return out


